#!/usr/bin/env python3
# tools/theme_catalog/gen_presets.py — tools/theme_catalog/warptempo_presets.txt -> THE BUILT-IN PALETTES' GENERATED
# INCLUDE, src/gui/palette_presets.inc (the rows of kGuiBuiltinPalettes, src/gui/palette_file.h, which owns what a
# palette is and does).
# ONE SOURCE: THE PROGRAM'S PRESETS, warptempo_presets.txt's, in its order (that file's head is their design and
# provenance: since 2026-10-26 Cool Edit Pro 2.1's twenty color presets, each as it is); the value grammar and the
# outline's lightness below are Cool Edit's.
# THE ORDER IS ALPHABETICAL BY DISPLAY NAME, case-insensitive (str.lower()), Default sorted among the names (architect
# 2026-10-27): the text's order is the include's and so the waveform value list's, and a name line out of that order is the
# run's hard fail, the first such row named — the text is reordered by hand, never sorted here.
# Each row a KEY, a DISPLAY NAME and THE PROGRAM ROLES (kGuiPaletteRoles, read off palette_file.h and checked
# against ROLE_ORDER) under the one transcription below.
#
# THE SOURCE, in Cool Edit's value grammar (comma-separated key=value items, its keys alone since the program's own
# Inv retired with the invalid color, architect 2026-10-26): EVERY values line is followed by its
# name line. A values line followed by another values line, or by the file's end, is the run's hard fail, the first
# such line named; a name line following no values line likewise. Lines opening with '#' are the file's note.
#
# THE TRANSCRIPTION, each role <- the preset's key, every key required, nothing derived but the outline:
#   waveform_canvas <- WvBk          waveform_ink <- WvFg          grid <- GrdL          center <- Cntr
#   cue <- CueM                      range <- RngM                 playhead_stem <- Curs
#   led <- _LED (Cool Edit's LED color, the lit lamps' accent verbatim, architect 2026-10-29: "just use the color");
#   face <- Face (the record; no surface reads it, palette_file.h's head);
#   waveform_outline <- THE INK AT HLS LIGHTNESS 0.3157, hue and saturation kept: the lightness was measured on Cool
#     Edit Pro 2.1's view bar span shadows across five of its presets (2026-10-09; src/gui/cool_edit_derive.h's
#     `span_shadow` record, its (a, b) read off that file and checked to be (0, 0.3157); the product's span itself is
#     neutral grey since 2026-10-25, materials.h), its round trip ported below operation for operation, so the
#     bytes are cool_edit_derive.h's tone() exactly (palette_file.cpp's static_assert proves every row);
#   scanner FFFFFF, the same in every preset (architect 2026-10-16, Cool Edit's own constant white, observed in Cool
#     Edit Pro 2.1 under Wine: the scanner is white on every preset he tried, so the value grammar records no key for
#     it; the zoom anchor's stem is the same design).
#   Any other key is read past and never generated (architect 2026-10-14: Cool Edit's other preset keys get no
#     palette role; _LED, one of them that day, taken 2026-10-29 by his own word).
# THE KEY is the display name lowercased, every run of other characters one hyphen, no prefix (architect 2026-10-27:
# "Grape, Lime, and Tangerine" -> `grape-lime-and-tangerine`, "CEPro 1.2" -> `cepro-1-2`), the `waveform` device key's
# word (a built-in's key alone since 2026-10-14); THE DISPLAY NAME is the source's own. Keys and display names are checked unique, every key in
# the key grammar (palette_file.cpp's is_preset_key_spelling, which bounds no length) and every display name
# printable ASCII within 40 bytes (the names' bound).
#
# BYTE-STABLE: the presets in the file's order, the roles in the table's, uppercase hex, LF, no timestamp; run it
# twice and the include is identical. THE INCLUDE IS ITS OUTPUT, NEVER HAND-EDITED: a change is the text, then this,
# the output committed with it.
#
#   python3 -I tools/theme_catalog/gen_presets.py [the presets text]
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

SOURCE = os.path.join(HERE, 'warptempo_presets.txt')
PALETTE_FILE_H = os.path.join(REPO, 'src', 'gui', 'palette_file.h')
COOL_EDIT_DERIVE_H = os.path.join(REPO, 'src', 'gui', 'cool_edit_derive.h')
PRESETS_INC = os.path.join(REPO, 'src', 'gui', 'palette_presets.inc')
GENERATED = '// GENERATED by tools/theme_catalog/gen_presets.py; never hand-edit.\n'

# THE ROLE TABLE'S ORDER (kGuiPaletteRoles), checked against the header at every run
ROLE_ORDER = ('waveform_canvas', 'waveform_ink', 'waveform_outline', 'grid', 'center', 'cue', 'range',
              'playhead_stem', 'scanner', 'led', 'face')
# role <- the preset's key (the head)
FROM_KEY = {'waveform_canvas': 'WvBk', 'waveform_ink': 'WvFg', 'grid': 'GrdL', 'center': 'Cntr', 'cue': 'CueM',
            'range': 'RngM', 'playhead_stem': 'Curs', 'led': '_LED', 'face': 'Face'}
# the role the value grammar has no key for (the head)
FIXED = {'scanner': 0xFFFFFF}
OUTLINE = (0.0, 0.3157)   # the span shadow's (a, b), checked against cool_edit_derive.h
TABLE_ROW = r'\{"([a-z_]+)",\s*&GuiPalette::\w+\}'


def role_table():
    """kGuiPaletteRoles' names read off src/gui/palette_file.h, in order."""
    text = open(PALETTE_FILE_H).read()
    body = text[text.index('kGuiPaletteRoles[] = {'):]
    body = body[:body.index('};')]
    return tuple(re.findall(TABLE_ROW, body))


def span_shadow_fit():
    """cool_edit_derive.h's `span_shadow` tone's (a, b)."""
    m = re.search(r'\{"span_shadow",\s*0x[0-9A-Fa-f]{6},\s*([-0-9.]+),\s*([-0-9.]+),', open(COOL_EDIT_DERIVE_H).read())
    if not m: raise SystemExit(f'gen_presets: no span_shadow tone in {COOL_EDIT_DERIVE_H}')
    return float(m.group(1)), float(m.group(2))


# -- THE HLS ROUND TRIP, cool_edit_derive.h's tone() operation for operation (Python's floats are its doubles) --------

def frac(x):
    t = x - float(int(x))
    return t + 1.0 if t < 0.0 else t


def rgb_to_hls(r, g, b):
    maxc = (r if r > b else b) if r > g else (g if g > b else b)
    minc = (r if r < b else b) if r < g else (g if g < b else b)
    sumc = maxc + minc
    rangec = maxc - minc
    l = sumc / 2.0
    if minc == maxc: return 0.0, l, 0.0
    s = rangec / sumc if l <= 0.5 else rangec / (2.0 - maxc - minc)
    rc = (maxc - r) / rangec
    gc = (maxc - g) / rangec
    bc = (maxc - b) / rangec
    if r == maxc:   h = bc - gc
    elif g == maxc: h = 2.0 + rc - bc
    else:           h = 4.0 + gc - rc
    return frac(h / 6.0), l, s


def hls_value(m1, m2, hue):
    hue = frac(hue)
    if hue < 1.0 / 6.0: return m1 + (m2 - m1) * hue * 6.0
    if hue < 0.5:       return m2
    if hue < 2.0 / 3.0: return m1 + (m2 - m1) * (2.0 / 3.0 - hue) * 6.0
    return m1


def byte_of(v):
    n = int(v * 255.0 + 0.5)
    return 0 if n < 0 else (255 if n > 255 else n)


def tone(face, a, b):
    h, fl, s = rgb_to_hls(float((face >> 16) & 0xFF) / 255.0, float((face >> 8) & 0xFF) / 255.0,
                          float(face & 0xFF) / 255.0)
    l = a * fl + b
    l = 0.0 if l < 0.0 else (1.0 if l > 1.0 else l)
    if s == 0.0:
        v = byte_of(l)
        return (v << 16) | (v << 8) | v
    m2 = l * (1.0 + s) if l <= 0.5 else l + s - l * s
    m1 = 2.0 * l - m2
    return (byte_of(hls_value(m1, m2, h + 1.0 / 3.0)) << 16) | (byte_of(hls_value(m1, m2, h)) << 8) | \
        byte_of(hls_value(m1, m2, h - 1.0 / 3.0))


# -- THE SOURCE ---------------------------------------------------------------------------------------------------

def parse_values(line):
    """One values line -> {key: value}."""
    out = {}
    for item in line.split(','):
        k, sep, v = item.partition('=')
        if not sep: raise SystemExit(f'gen_presets: not a key=value item: {item!r}')
        if k in out: raise SystemExit(f'gen_presets: duplicate key {k} in {line!r}')
        out[k] = v
    return out


def presets(path):
    """The source -> [(display name, {key: value})] in the file's order (the head's pairing)."""
    lines = [ln for ln in open(path, newline='\n').read().split('\n') if ln and not ln.startswith('#')]
    if not lines: raise SystemExit(f'gen_presets: {path} holds no preset')
    out = []
    pending = None   # the values line still waiting for its name line
    for ln in lines:
        if '=' in ln:
            if pending is not None:
                raise SystemExit(f'gen_presets: the values line {pending!r} is followed by no name line')
            out.append([None, parse_values(ln)])
            pending = ln
        else:
            if pending is None: raise SystemExit(f'gen_presets: the name line {ln!r} follows no values line')
            out[-1][0] = ln
            pending = None
    if pending is not None:
        raise SystemExit(f'gen_presets: the values line {pending!r} is followed by no name line')
    return [tuple(p) for p in out]


def word(values, key, name):
    v = values.get(key)
    if v is None or not re.fullmatch(r'[0-9A-Fa-f]{6}', v):
        raise SystemExit(f'gen_presets: {name} records no six-digit {key}: {v!r}')
    return int(v, 16)


def preset_words(name, values):
    """One preset -> its words in ROLE_ORDER (the head's transcription)."""
    w = {role: word(values, key, name) for role, key in FROM_KEY.items()}
    w['waveform_outline'] = tone(w['waveform_ink'], *OUTLINE)
    w.update(FIXED)
    return [w[r] for r in ROLE_ORDER]


def preset_key(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def all_presets(source=SOURCE):
    """The source -> [(key, display name, {key: value})] in its order (the head)."""
    return [(preset_key(n), n, v) for n, v in presets(source)]


def main():
    if len(sys.argv) > 2:
        raise SystemExit('usage: python3 -I tools/theme_catalog/gen_presets.py [the presets text]')
    source = sys.argv[1] if len(sys.argv) == 2 else SOURCE
    if role_table() != ROLE_ORDER:
        raise SystemExit(f'gen_presets: {PALETTE_FILE_H}\'s kGuiPaletteRoles is {role_table()}, not ROLE_ORDER')
    if span_shadow_fit() != OUTLINE:
        raise SystemExit(f'gen_presets: {COOL_EDIT_DERIVE_H}\'s span_shadow is {span_shadow_fit()}, not {OUTLINE}')
    ps = all_presets(source)
    keys = [k for k, _, _ in ps]
    names = [n for _, n, _ in ps]
    for a, b in zip(names, names[1:]):
        if b.lower() < a.lower():
            raise SystemExit(f'gen_presets: the name line {b!r} is out of alphabetical order (after {a!r})')
    for what, xs in (('key', keys), ('display name', names)):
        dup = sorted({x for x in xs if xs.count(x) > 1})
        if dup: raise SystemExit(f'gen_presets: duplicate preset {what}s: {dup}')
    for k in keys:
        if not re.fullmatch(r'[a-z0-9]+(-[a-z0-9]+)*', k):
            raise SystemExit(f'gen_presets: the key {k!r} is outside the key grammar')
    for n in names:
        if not (0 < len(n) <= 40 and all(0x20 <= ord(c) <= 0x7E for c in n) and n == n.strip() and '/' not in n
                and '"' not in n and '\\' not in n):
            raise SystemExit(f'gen_presets: the display name {n!r} is outside the palette name grammar')
    rows = ''.join(f'    {{"{k}", "{n}", {{{", ".join(f"0x{w:06X}" for w in preset_words(n, v))}}}}},\n'
                   for k, n, v in ps)
    with open(PRESETS_INC, 'w', newline='\n') as f:
        f.write(GENERATED +
                '// THE BUILT-IN PALETTES (src/gui/palette_file.h\'s kGuiBuiltinPalettes, included in its initializer): '
                'the program\'s\n'
                '// presets in their text\'s order, alphabetical by display name (tools/theme_catalog/warptempo_presets.txt); '
                'each its\n'
                '// key, its display name and its words in kGuiPaletteRoles\' order under the generator\'s rules; '
                'regenerate, never hand-edit.\n' + rows)
    print(f'wrote {os.path.relpath(PRESETS_INC, REPO)}: {len(ps)} built-in palettes')


if __name__ == '__main__':
    main()
