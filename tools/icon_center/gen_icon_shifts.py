#!/usr/bin/env python3
"""GENERATOR of src/gui/icon_shifts.inc: the body-centering shift of every
glyph of the one set, assets/icons/adwaita-3.22/*.svg (architect 2026-10-12;
the set Adwaita 3.22.0 since 2026-10-14). Run from anywhere:
    python3 tools/icon_center/gen_icon_shifts.py
The body is the drawing with its shadows removed STRUCTURALLY (an element under a
feGaussianBlur filter, a fill of a radial gradient fading to transparent, an id or
inkscape:label containing "shadow"); its alpha >= 0.1 bounds at 240 px; the shift
puts the bbox center at the viewBox center, in the SVG's user units. The slot
nested in each file as its own <svg> viewport is walked like any group."""
import re, sys, io, subprocess, os, tempfile, numpy as np
import xml.etree.ElementTree as ET
from PIL import Image
R=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))+'/'
SET=R+'assets/icons/adwaita-3.22/'
SV='{http://www.w3.org/2000/svg}'; XL='{http://www.w3.org/1999/xlink}'
INK='{http://www.inkscape.org/namespaces/inkscape}'
def url(v):
    m=re.search(r'url\(#([^)]+)\)',v or ''); return m.group(1) if m else None
def prop(e,k):
    if e.get(k): return e.get(k)
    m=re.search(r'(?:^|;)\s*'+k+r'\s*:\s*([^;]+)',e.get('style',''))
    return m.group(1).strip() if m else None
def strip(path):
    tree=ET.parse(path); root=tree.getroot()
    byid={e.get('id'):e for e in root.iter() if e.get('id')}
    def blur(fid):
        f=byid.get(fid)
        if f is None: return None
        for g in f.iter(SV+'feGaussianBlur'): return g.get('stdDeviation')
    def fades(gid,seen=()):
        g=byid.get(gid)
        if g is None or g.tag!=SV+'radialGradient' and g.tag!=SV+'linearGradient': return False
        stops=list(g.iter(SV+'stop'))
        if not stops:
            h=g.get(XL+'href') or g.get('href')
            return fades(h[1:],seen) if h and h[1:] not in seen else False
        if g.tag!=SV+'radialGradient':
            h=None
        s=stops[-1]; op=prop(s,'stop-opacity')
        return g.tag==SV+'radialGradient' and op is not None and float(op)<0.05
    def radial_fades(gid):
        g=byid.get(gid)
        if g is None: return False
        # radial gradient may href a stops-only gradient
        h=g.get(XL+'href') or g.get('href'); stops=list(g.iter(SV+'stop'))
        src=g if stops else (byid.get(h[1:]) if h else None)
        if g.tag!=SV+'radialGradient' or src is None: return False
        st=list(src.iter(SV+'stop'))
        if not st: return False
        op=prop(st[-1],'stop-opacity')
        return op is not None and float(op)<0.05
    removed=[]
    def walk(parent,anc_blur):
        for ch in list(parent):
            if ch.tag in (SV+'defs',SV+'metadata',SV+'linearGradient',SV+'radialGradient',SV+'filter',SV+'clipPath',SV+'mask'): continue
            why=None
            fid=url(prop(ch,'filter'))
            if fid and blur(fid): why=f'blur{blur(fid)}'
            fl=url(prop(ch,'fill'))
            if not why and fl and radial_fades(fl): why='radfade'
            lab=(ch.get('id') or '')+(ch.get(INK+'label') or '')
            if not why and 'shadow' in lab.lower(): why='name:'+lab
            if why:
                removed.append(f"{ch.get('id') or ch.tag.split('}')[1]}:{why}"); parent.remove(ch)
            else: walk(ch,anc_blur)
    walk(root,None)
    vb=[float(x) for x in root.get('viewBox','0 0 48 48').replace(',',' ').split()]
    return tree,removed,vb
def rsvg(path,size):
    out=subprocess.run(['rsvg-convert','-w',str(size),'-h',str(size),path],capture_output=True).stdout
    return Image.open(io.BytesIO(out)).convert('RGBA')
def bbox(im,thr):
    a=np.asarray(im)[...,3]/255.0; ys,xs=np.where(a>=thr)
    return (xs.min(),xs.max()+1,ys.min(),ys.max()+1) if len(xs) else None
def main():
    h=open(R+'src/gui/icons.h').read()
    blk=h[h.index('kIconNames[] = {'):]; blk=blk[:blk.index('};')]
    names=re.findall(r'"(\w+)"',blk)
    tmp=tempfile.mkdtemp()
    lines=[]
    for n in names:
        tree,rem,vb=strip(SET+n+'.svg'); p=tmp+'/'+n+'.svg'; tree.write(p)
        b=bbox(rsvg(p,240),0.1); u=vb[2]/240
        cx=(b[0]+b[1])/2*u+vb[0]; cy=(b[2]+b[3])/2*u+vb[1]
        dx=round(vb[0]+vb[2]/2-cx,1)+0.0; dy=round(vb[1]+vb[3]/2-cy,1)+0.0
        lines.append('{"%s", %.1ff, %.1ff},'%(n,dx,dy))
    with open(R+'src/gui/icon_shifts.inc','w') as f:
        f.write('// GENERATED by tools/icon_center/gen_icon_shifts.py; never hand-edited.\n'
                '// One body-centering shift (dx, dy) per glyph in kIconNames order, SVG user units.\n')
        f.write('\n'.join(lines)+'\n')
if __name__=='__main__': main()
